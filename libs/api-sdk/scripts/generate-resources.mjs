import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { operationNames } from './operation-names.mjs';

const spec = YAML.parse(
  await readFile(new URL('../../../apps/api/openapi.yaml', import.meta.url), 'utf8'),
);
const check = process.argv.includes('--check');
const operations = [];
const names = new Set();
const title = (s) => s[0].toUpperCase() + s.slice(1);
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of ['get', 'post', 'put', 'patch', 'delete', 'head', 'options']) {
    const op = item[method];
    if (!op) continue;
    if (!op.operationId) throw new Error(`Missing operationId: ${method} ${path}`);
    const { helper: name } = operationNames(op.operationId, method);
    if (names.has(name)) throw new Error(`Duplicate operation name: ${name}`);
    names.add(name);
    const parameters = [...(item.parameters ?? []), ...(op.parameters ?? [])];
    const required = Boolean(op.requestBody?.required || parameters.some((p) => p.required));
    const success = Object.entries(op.responses).filter(([status]) => /^2/.test(status));
    const binary = success.some(([, r]) => r.content?.['application/octet-stream']);
    const html = success.some(([, r]) => r.content?.['text/html']);
    const empty = success.every(([, r]) => !r.content);
    const multipart = Boolean(op.requestBody?.content?.['multipart/form-data']);
    operations.push({ path, method, op, name, required, binary, html, empty, multipart });
  }
}
operations.sort((a, b) => a.name.localeCompare(b.name));
let shared = `// Generated by scripts/generate-resources.mjs. Do not edit.\nimport type { FetchOptions } from 'openapi-fetch';\nimport type { ApiSdk } from './client.js';\nimport { ApiSdkError, unwrap } from './errors.js';\nimport type { paths } from './generated.js';\n`;
let react = `// Generated by scripts/generate-resources.mjs. Do not edit.\nimport { mutationOptions, type QueryClient, type QueryKey, queryOptions, type UseQueryOptions, useMutation, useQuery, useQueryClient } from '@tanstack/react-query';\nimport type { ApiSdk } from '../shared/client.js';\nimport * as api from '../shared/resources.js';\nimport { useApiSdk } from './provider.js';\n\n/** All generated operation caches; scoped to the QueryClient's authenticated session. */\nexport const apiKeys = { all: ['api'] as const, operation: (operationId: string, params?: unknown) => ['api', operationId, params ?? {}] as const };\n\ntype QuerySettings<T> = Omit<UseQueryOptions<T>, 'queryFn' | 'queryKey'> & { queryKey?: QueryKey };\nexport type ApiMutationSettings = { invalidate?: readonly QueryKey[] };\nconst invalidate = (client: QueryClient, settings?: ApiMutationSettings) => Promise.all((settings?.invalidate ?? [apiKeys.all]).map(queryKey => client.invalidateQueries({ queryKey })));\n`;
for (const { path, method, op, name, required, binary, html, empty, multipart } of operations) {
  const type = title(name);
  const input = `${type}Input`;
  shared += `\n/** ${method.toUpperCase()} ${path} (${op.operationId}). */\nexport type ${input} = Omit<FetchOptions<paths[${JSON.stringify(path)}][${JSON.stringify(method)}]>, 'parseAs'${multipart ? " | 'body' | 'bodySerializer'" : ''}>${multipart ? ' & { body: FormData }' : ''};\n`;
  const init = required ? `input: ${input}` : `input: ${input} = {}`;
  shared += `export async function ${name}(sdk: ApiSdk, ${init}) {\n`;
  const opts = binary ? ", parseAs: 'blob'" : html ? ", parseAs: 'text'" : '';
  // FormData is a transport representation of the binary OpenAPI body, not a JSON object.
  const callInit = multipart
    ? `{ ...input, body: input.body as unknown as paths[${JSON.stringify(path)}][${JSON.stringify(method)}]['requestBody']['content']['multipart/form-data'], bodySerializer: () => input.body }`
    : `{ ...input${opts} }`;
  shared += `const result = await sdk.${method.toUpperCase()}(${JSON.stringify(path)}, ${callInit});\n`;
  if (empty)
    shared += `if (!result.response.ok) throw new ApiSdkError(result.response.status, result.error);\nreturn;\n`;
  else shared += `return unwrap(result);\n`;
  shared += '}\n';
  if (method === 'get') {
    react += `\nexport function ${name}QueryOptions(sdk: ApiSdk, ${required ? `input: api.${input}` : `input: api.${input} = {}`}, settings?: QuerySettings<Awaited<ReturnType<typeof api.${name}>>>) {\nreturn queryOptions({ ...settings, queryKey: settings?.queryKey ?? apiKeys.operation(${JSON.stringify(op.operationId)}, input.params), queryFn: ({signal}) => api.${name}(sdk, { ...input, signal }) });\n}\nexport function use${type}(${required ? `input: api.${input}` : `input: api.${input} = {}`}, settings?: QuerySettings<Awaited<ReturnType<typeof api.${name}>>>) {\nreturn useQuery(${name}QueryOptions(useApiSdk(), input, settings));\n}\n`;
  } else {
    react += `\nexport function ${name}MutationOptions(sdk: ApiSdk, client: QueryClient, settings?: ApiMutationSettings) {\nreturn mutationOptions({ mutationFn: (input: api.${input}) => api.${name}(sdk, input), retry: false, onSuccess: () => invalidate(client, settings) });\n}\nexport function use${type}(settings?: ApiMutationSettings) {\nreturn useMutation(${name}MutationOptions(useApiSdk(), useQueryClient(), settings));\n}\n`;
  }
}
shared += `\nexport const apiOperations = {\n${operations.map(({ name }) => `${name},`).join('\n')}\n};\n`;
const manifest = operations.map(({ path, method, op, name, binary, html, empty, multipart }) => ({
  operationId: op.operationId,
  name,
  method,
  path,
  tag: op['x-resource'] ?? op.tags?.[0],
  platform: op['x-platform'],
  hook: operationNames(op.operationId, method).hook,
  resourceHook: op['x-sdk']?.resourceHook,
  response: binary ? 'blob' : html ? 'text' : empty ? 'empty' : 'json',
  multipart,
}));
for (const [file, source] of [
  ['../src/shared/resources.ts', shared],
  ['../src/react/resources.ts', react],
]) {
  const target = new URL(file, import.meta.url);
  const result = spawnSync(
    'pnpm',
    ['-w', 'exec', 'biome', 'format', `--stdin-file-path=${fileURLToPath(target)}`],
    {
      input: source,
      encoding: 'utf8',
      maxBuffer: 20 * 1024 * 1024,
      shell: process.platform === 'win32',
    },
  );
  if (result.status !== 0) throw new Error(result.stderr || `Formatting failed: ${file}`);
  if (check) {
    if ((await readFile(target, 'utf8')) !== result.stdout)
      throw new Error(`Stale ${file}; run pnpm --filter @p4/api-sdk generate.`);
  } else await writeFile(target, result.stdout);
}
const manifestPath = new URL('../src/shared/operations.json', import.meta.url);
const json = `${JSON.stringify(manifest, null, 2)}\n`;
if (check) {
  if ((await readFile(manifestPath, 'utf8')) !== json)
    throw new Error('Operation manifest is stale.');
} else await writeFile(manifestPath, json);
console.log(`${check ? 'Checked' : 'Generated'} ${operations.length} API operations and hooks.`);

const referencePath = new URL('../../../documents/backend/api-sdk-reference.md', import.meta.url);
const groups = ['storefront', 'admin', 'shared', 'integration', 'operations'].filter((platform) =>
  manifest.some((op) => op.platform === platform),
);
const reference =
  '# API và SDK theo platform\n\nTự sinh từ OpenAPI; không sửa tay. Platform là nhóm sử dụng, không thay thế permission/ownership.\n\nHooks: `@p4/api-sdk/react`. Helpers và input: `@p4/api-sdk/shared`. Mọi helper nhận SDK trước input; hooks GET nhận input/settings, hooks mutation trả `mutate`/`mutateAsync`.\n\n' +
  groups
    .map(
      (platform) =>
        `## ${platform[0].toUpperCase()}${platform.slice(1)}\n\n| Method | Endpoint | Hook | Helper | Resource hook |\n| --- | --- | --- | --- | --- |\n` +
        manifest
          .filter((op) => op.platform === platform)
          .map(
            (op) =>
              `| ${op.method.toUpperCase()} | \`${op.path}\` | \`${op.hook}\` | \`${op.name}\` | ${op.resourceHook ? `\`${op.resourceHook}\`` : '—'} |`,
          )
          .join('\n'),
    )
    .join('\n\n') +
  '\n';
if (check) {
  if ((await readFile(referencePath, 'utf8')) !== reference)
    throw new Error('API/SDK reference is stale.');
} else await writeFile(referencePath, reference);
